end

function T = i_parameter_audit(params, density, cpmGrid, modularityGrid)
C = params.config_table;
T = table(string(C.parameter), string(C.effective_value), ...
    repmat("config", height(C), 1), false(height(C), 1), ...
    string(C.description), ...
    'VariableNames', {'parameter', 'effective_value', 'source', ...
    'used_for_partitioning', 'description'});
partitionParameters = ["backend_id", "primary_objective", ...
    "cpm_resolution_rule", "cpm_density_multipliers_full", ...
    "cpm_density_multipliers_smoke", "cpm_seeds_full", ...
    "cpm_seeds_smoke", "enable_modularity_challenger", ...
    "modularity_resolutions_full", "modularity_resolutions_smoke", ...
    "modularity_seeds_full", "modularity_seeds_smoke", ...
    "leiden_randomness", "iteration_mode", "maximum_iterations", ...
    "reference_partition_rule", "retention_min_pairwise_ari", ...
    "retention_max_normalized_vi", ...
    "retention_min_candidate_count", ...
    "retention_max_candidate_count", ...
    "retention_max_candidate_count_relative_range", ...
    "retention_max_singleton_node_fraction", ...
    "small_candidate_max_nodes", ...
    "retention_max_small_candidate_node_fraction", ...
    "retention_min_mean_node_stability", ...
    "ambiguity_min_node_stability", ...
    "hierarchy_min_child_parent_fraction", ...
    "hierarchy_min_pair_weighted_child_purity", ...
    "hierarchy_min_linked_node_fraction", ...
    "consensus_partition_rule", "consensus_split_rule", ...
    "consensus_refinement_seed", ...
    "consensus_retention_min_split_ari", ...
    "consensus_retention_max_normalized_vi", ...
    "consensus_retention_min_mean_node_stability", ...
    "consensus_retention_min_mean_vote_support"];
T.used_for_partitioning = ismember(T.parameter, partitionParameters);
if isfinite(density)
    derived = table( ...
        ["weighted_graph_density"; "active_cpm_resolution_grid"; ...
         "active_modularity_resolution_grid"; "active_cpm_seeds"; ...
         "active_modularity_seeds"; "partition_input_columns"; ...
         "experimental_labels_used_for_partitioning"], ...
        [compose('%.17g', density); i_join_numeric(cpmGrid); ...
         i_join_numeric(modularityGrid); ...
         i_join_numeric(params.active_cpm_seeds); ...
         i_join_numeric(params.active_modularity_seeds); ...
         "source_index;target_index;consensus_edge_weight"; "none"], ...
        repmat("derived_after_frozen_adapter", 7, 1), ...
        [true; true; true; true; true; true; false], ...
        [ ...
         "Total consensus weight divided by the number of possible undirected pairs."
         "Density-scaled primary weighted CPM resolutions."
         "Canonical weighted modularity challenger resolutions."
         "Deterministic CPM seeds active in this run mode."
         "Deterministic modularity challenger seeds active in this run mode."
         "Exact numeric fields reaching the weighted native graph."
         "Explicit scientific exclusion contract."
         ], ...
        'VariableNames', T.Properties.VariableNames);
    T = [T; derived];
end
end

function value = i_join_numeric(x)
if isempty(x)
    value = "";
else
    value = strjoin(compose('%.17g', x(:)'), ';');
end
end
