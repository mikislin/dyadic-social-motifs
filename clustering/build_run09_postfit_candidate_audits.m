T = readtable(pathText, opts);
end

function values = i_logical(valuesIn)
if islogical(valuesIn)
    values = valuesIn;
elseif isnumeric(valuesIn)
    values = valuesIn ~= 0;
else
    text = lower(strip(string(valuesIn)));
    assert(all(ismember(text, ...
        ["0","1","false","true","no","yes"])), ...
        'build_run09_postfit_candidate_audits:BadLogical', ...
        'A post-fit provenance flag is not logical-like.');
    values = ismember(text, ["1","true","yes"]);
end
values = logical(values);
end
