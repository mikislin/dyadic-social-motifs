function value = i_quantile(x, probability)
x = sort(double(x(:)));
if isempty(x)
    value = NaN;
    return
end
position = 1 + (numel(x) - 1) * probability;
lowerIndex = floor(position);
upperIndex = ceil(position);
if lowerIndex == upperIndex
    value = x(lowerIndex);
else
    value = x(lowerIndex) + (position - lowerIndex) * ...
        (x(upperIndex) - x(lowerIndex));
end
end

